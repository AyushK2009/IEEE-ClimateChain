"""Deploy to a public testnet (default: Base Sepolia) and run one full net lifecycle there,
so anyone can inspect real transactions on a block explorer. Play money only.

    python -m engine.testnet new-wallet     # make a fresh, testnet-only wallet; prints the address to fund
    python -m engine.testnet status         # show the funding address and balances
    python -m engine.testnet run            # deploy + register -> lose -> price -> claim -> verify -> pay

The wallet is generated locally and stored in .env (gitignored). Never put real funds in it.
"""
import json
import os
import sys
import time

import numpy as np
from eth_account import Account

from engine import config as C

ENV_FILE = C.ROOT / ".env"
OUT = C.RUNTIME / "testnet.json"
DEFAULT_RPC = "https://sepolia.base.org"
EXPLORER = "https://sepolia.basescan.org"


def _env():
    vals = {k: os.environ[k] for k in ("TESTNET_MNEMONIC", "TESTNET_RPC") if k in os.environ}   # env overrides .env
    if ENV_FILE.exists():
        for line in ENV_FILE.read_text().splitlines():
            if "=" in line and not line.strip().startswith("#"):
                k, v = line.split("=", 1)
                vals.setdefault(k.strip(), v.strip())
    return vals


def new_wallet():
    if "TESTNET_MNEMONIC" in _env():
        print("A testnet wallet already exists in .env; not overwriting it.")
        return status()
    Account.enable_unaudited_hdwallet_features()
    acct, mnemonic = Account.create_with_mnemonic()
    with ENV_FILE.open("a") as f:
        f.write(f"\n# Testnet-only wallet generated by engine/testnet.py. Play money only; never send real funds.\n"
                f"TESTNET_MNEMONIC={mnemonic}\nTESTNET_RPC={DEFAULT_RPC}\n")
    print(f"Created a testnet-only wallet. Fund this address with Base Sepolia test ETH (about 0.02 is plenty):\n  {acct.address}")


def _chain():
    env = _env()
    if "TESTNET_MNEMONIC" not in env:
        sys.exit("No testnet wallet yet. Run: python -m engine.testnet new-wallet")
    os.environ["ACTOR_MNEMONIC"] = env["TESTNET_MNEMONIC"]
    from engine.chain import Chain
    return Chain(env.get("TESTNET_RPC", DEFAULT_RPC))


def status():
    ch = _chain()
    print(f"RPC {ch.rpc} chain id {ch.chain_id}")
    for k in ("admin", "supplier", "sponsor", "kai", "crew_a"):
        print(f"  {k:9s} {ch.addr(k)}  {ch.w3.eth.get_balance(ch.addr(k)) / 1e18:.5f} ETH")


def run():
    from engine import forecast as F
    from engine import merkle as M
    from engine import pricing as P
    from engine import scenario as S
    from engine import tags as T
    from engine import verify as VF
    from engine import vision as V
    from eth_utils import keccak

    F.DIR = C.RUNTIME / "testnet_forecasts"     # never touch the local demo's forecast files
    F.load.cache_clear()
    ch = _chain()
    w3 = ch.w3
    funder = ch.addr("admin")
    bal = w3.eth.get_balance(funder) / 1e18
    if bal < 0.0008:
        sys.exit(f"Funding address {funder} has {bal:.5f} ETH; request Base Sepolia test ETH from a faucet first.")
    log = {"chainId": ch.chain_id, "explorer": EXPLORER, "steps": []}

    def step(label, tx):
        log["steps"].append({"label": label, "tx": tx.hash, "url": f"{EXPLORER}/tx/{tx.hash}"})
        print(f"  {label}: {EXPLORER}/tx/{tx.hash}")

    print("Funding actor gas (testnet ETH)...")
    for k in ("supplier", "sponsor", "kai", "crew_a", "crew_b"):     # Base Sepolia fees are ~0.01 gwei: 0.0001 ETH is many transactions
        if w3.eth.get_balance(ch.addr(k)) < 5 * 10**13:
            tx = {"to": ch.addr(k), "value": 10**14, "nonce": w3.eth.get_transaction_count(funder, "pending"),
                  "chainId": ch.chain_id, "gas": 21000, "maxFeePerGas": w3.eth.gas_price * 2 + 10**8,
                  "maxPriorityFeePerGas": 10**8}
            h = w3.eth.send_raw_transaction(ch.accounts["admin"].sign_transaction(tx).raw_transaction)
            w3.eth.wait_for_transaction_receipt(h, timeout=180)
    print("Deploying contracts...")
    usd, esc = ch.deploy()
    log.update(usd=usd, escrow=esc, escrowUrl=f"{EXPLORER}/address/{esc}")
    print(f"  GearEscrow {EXPLORER}/address/{esc}")
    ch.mint("kai", 5_000); ch.approve_escrow("kai")
    ch.mint("sponsor", 50_000); ch.approve_escrow("sponsor")
    t, ids = ch.register("kai", 3, C.DEPOSIT); step(f"Checkout: 3 net passports minted ({ids})", t)
    t = ch.sponsor("sponsor", 20_000); step("Sponsor funds the bounty pool (20,000 dUSD play money)", t)
    net = ids[0]
    sug = S.FEATURED_SUGGESTION
    from engine import drift as D
    loss_day = D.currents().day_index(S.TODAY)
    other = ids[1]                                   # a second lost net: the target of the fraud attempt
    t = ch.report_loss("kai", [net, other], [keccak(f"{n}|{sug['lat']}|{sug['lon']}|{loss_day}".encode()) for n in (net, other)])
    step(f"Nets #{net} and #{other} reported lost (deposits move to the reward pool)", t)
    F.run_group([net, other], np.array([sug["lat"]] * 2), np.array([sug["lon"]] * 2), loss_day, 500)
    claim_day = loss_day + 21
    epoch = ch.current_epoch() + 1
    b = P.build([{"id": n, "owner": "kai", "loss_day": loss_day, "deposit": C.DEPOSIT} for n in (net, other)], claim_day,
                ch.pool()["poolAvailable"], epoch)
    t = ch.publish_epoch(bytes.fromhex(b["root"][2:]), b["total"] * 10**18, f"price-list/epoch-{epoch}.json")
    e = next(x for x in b["entries"] if x["netId"] == net)
    step(f"Daily price list sealed as a Merkle root (net #{net}: {e['bounty']} dUSD)", t)
    lat, lon, _ = F.at(net, claim_day)
    i = int(np.argmin((lat - np.median(lat)) ** 2 + (lon - np.median(lon)) ** 2))
    photo = T.to_jpeg(T.staged_photo(T.tag_image(ch.chain_id, esc, net, "Kai Fisheries"), "recovered", 0))
    t, cid = ch.submit_claim("crew_a", net, e["bounty"] * 10**18, epoch, [bytes.fromhex(p[2:]) for p in e["proof"]], keccak(photo))
    step(f"Recovery claim submitted (bounty locked)", t)
    ai = V.check(photo)
    outcome, report, rh = VF.run({"id": net, "loss_day": loss_day, "loss_lat": sug["lat"], "loss_lon": sug["lon"],
                                  "chainStatus": "Lost"},
                                 {"claimant": "crew_a", "day": claim_day, "lat": float(lat[i]), "lon": float(lon[i]),
                                  "tag": T.decode(photo), "photo_hash": "0x" + keccak(photo).hex()}, ai)
    t = ch.resolve_claim(cid, outcome, rh); step(f"Verifier records outcome: {outcome} (paid automatically)", t)
    log["outcome"] = outcome
    log["report"] = report
    OUT.write_text(json.dumps(log, indent=1, default=str))
    # fraud attempt: a printed copy of the other net's tag, no net in the photo
    e2 = next(x for x in b["entries"] if x["netId"] == other)
    fake = T.to_jpeg(T.staged_photo(T.tag_image(ch.chain_id, esc, other, "Kai Fisheries"), "printout", 1))
    t, cid2 = ch.submit_claim("crew_b", other, e2["bounty"] * 10**18, epoch, [bytes.fromhex(p[2:]) for p in e2["proof"]], keccak(fake))
    step(f"Fraud attempt on net #{other}: printed tag, no net (bounty locked)", t)
    ai2 = V.check(fake)
    outcome2, report2, rh2 = VF.run({"id": other, "loss_day": loss_day, "loss_lat": sug["lat"], "loss_lon": sug["lon"], "chainStatus": "Lost"},
                                    {"claimant": "crew_b", "day": claim_day, "lat": float(lat[i]), "lon": float(lon[i]),
                                     "tag": T.decode(fake), "photo_hash": "0x" + keccak(fake).hex()}, ai2)
    t = ch.resolve_claim(cid2, outcome2, rh2); step(f"Verifier records outcome: {outcome2} (locked bounty returns to the pool)", t)
    log["fraudOutcome"] = outcome2
    OUT.write_text(json.dumps(log, indent=1, default=str))
    print(f"Done. Summary with explorer links: {OUT.relative_to(C.ROOT)}")


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "status"
    {"new-wallet": new_wallet, "status": status, "run": run}[cmd]()
